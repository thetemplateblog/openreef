"""Build a 3D OpenSCAD assembly of the finger-jointed enclosure from panels.py geometry,
so the joints can be checked visually (and exported as STL for a CAD viewer).
Run: python assembly.py  -> enclosure_assembly.scad ; then
     openscad -o renders/enclosure_assembly.png --autocenter --viewall enclosure_assembly.scad
"""
import panels as P

def scad_polygon(poly):
    rings = [list(poly.exterior.coords)[:-1]] + [list(r.coords)[:-1] for r in poly.interiors]
    pts, paths, n = [], [], 0
    for r in rings:
        paths.append(list(range(n, n + len(r)))); pts += [[round(x, 3), round(y, 3)] for x, y in r]; n += len(r)
    return f"polygon(points={pts}, paths={paths});"

def panel_module(p):
    body = scad_polygon(p.shape)
    holes = " ".join(scad_polygon(h) for h in p.holes)
    return f"module {p.name}() {{ linear_extrude({p.t}) difference() {{ {body} {holes} }} }}"

W, H, D, T3, T6, BX = P.W, P.H, P.D, P.T3, P.T6, P.BULK_X
# flat (x,y) -> 3D placement. Flat plane XY is extruded along +Z by thickness.
PLACE = {
    # side: flat x = depth from back (-> world y), flat y = height (-> world z); thickness along world x
    "SIDE_L":    f"translate([0,0,0]) rotate([90,0,90])",
    "SIDE_R":    f"translate([{W-T3},0,0]) rotate([90,0,90])",
    "BASE":      f"translate([0,0,0])",                                  # x width, y depth, z 0..6
    "TOP":       f"translate([0,0,{H-T3}])",
    "BACK":      f"translate([0,{T6},0]) rotate([90,0,0])",             # x width, y height -> z; thickness toward -y => occupies y 0..6
    "BULKHEAD":  f"translate([{BX-T3/2},{T6},{T6}]) rotate([90,0,90])", # flat x depth -> y, flat y height -> z
    "SHELF_1":   f"translate([{T3},{T6},{T6+P.SHELF_Z[0]}])",
    "SHELF_2":   f"translate([{T3},{T6},{T6+P.SHELF_Z[1]}])",
    "SHELF_3":   f"translate([{T3},{T6},{T6+P.SHELF_Z[2]}])",
    "FRONT_DRY": f"translate([{BX+T3/2},{D},0]) rotate([90,0,0])",      # occupies y D-3..D
}
COLOR = {"SIDE_L": "#9fd8d6", "SIDE_R": "#9fd8d6", "BASE": "#4a5553", "BACK": "#4a5553", "TOP": "#dff1f0",
         "BULKHEAD": "#e4572e", "SHELF_1": "#c98a1a", "SHELF_2": "#c98a1a", "SHELF_3": "#c98a1a", "FRONT_DRY": "#0f8b8d"}

panels = {p.name: p for p in P.build(kerf=0.18, fit=0.0, tslot=True)}   # fit 0 for a clean visual check
out = ["// OpenReef enclosure assembly — generated by assembly.py from panels.py", "$fn = 24;",
       "explode = 0;   // set e.g. 40 to pull panels apart"]
for name, p in panels.items():
    if name == "DOOR": continue
    out.append(panel_module(p))
out.append("module assembly() {")
offsets = {"SIDE_L": "[-explode,0,0]", "SIDE_R": "[explode,0,0]", "TOP": "[0,0,explode]", "BACK": "[0,-explode,0]",
           "FRONT_DRY": "[0,explode,0]", "BASE": "[0,0,-explode]"}
for name in PLACE:
    out.append(f'  color("{COLOR[name]}") translate({offsets.get(name, "[0,0,0]")}) {PLACE[name]} {name}();')
out.append("}")
out.append("// Mirrored so the wet bay is on the LEFT as you face the door; a flipped acrylic panel is the same part.")
out.append(f"translate([{W},0,0]) mirror([1,0,0]) assembly();")
open("enclosure_assembly.scad", "w").write("\n".join(out))
print("wrote enclosure_assembly.scad")
